package io.github.s3s3l.yggdrasil.game.core.ui;

/**
 * UI 锚点
 * 用于确定 UI 组件的定位基准点
 */
public enum UIAnchor {
    /**
     * 左上角
     */
    TOP_LEFT,

    /**
     * 上中点
     */
    TOP_CENTER,

    /**
     * 右上角
     */
    TOP_RIGHT,

    /**
     * 左中点
     */
    MIDDLE_LEFT,

    /**
     * 中心点
     */
    CENTER,

    /**
     * 右中点
     */
    MIDDLE_RIGHT,

    /**
     * 左下角
     */
    BOTTOM_LEFT,

    /**
     * 下中点
     */
    BOTTOM_CENTER,

    /**
     * 右下角
     */
    BOTTOM_RIGHT
}
